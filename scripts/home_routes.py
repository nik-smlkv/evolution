"""Generate portable static aliases of the homepage from one reviewed route map.

The original homepage remains the sole source of content and metadata. Each
alias adds a document base so assets and links still resolve from the site root,
including when the site is hosted in a project subdirectory.
"""

import json
import re
from collections import Counter
from html.parser import HTMLParser
from pathlib import Path
from localized_pages import LOCALE_CONFIG, TRANSLATIONS, read_strings, render_english_page


CONFIG_PATH = "config/site-routes.json"
MODULE_PATH = "js/home-routes.js"
GENERATOR = "python3 scripts/generate-home-routes.py"
MODULE_MARKER = "// Generated by scripts/generate-home-routes.py; edit config/site-routes.json."
HTML_MARKER = "<!-- Generated by scripts/generate-home-routes.py; edit index.html instead. -->"
SLUG = re.compile(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*\Z", re.ASCII)
TARGET_ID = re.compile(r"[A-Za-z][A-Za-z0-9_-]*\Z", re.ASCII)
RESERVED_SLUGS = {
    "archive", "assets", "config", "dist", "en", "fonts", "index", "js",
    "scripts", "search-by-parameters", "style", "tests", "videos",
}


class HomeRouteError(ValueError):
    """Invalid configuration, unsafe output or stale generated homepage alias."""


def _read(path):
    try:
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeError) as error:
        raise HomeRouteError("Cannot read {}: {}".format(path, error)) from error


def _local_path(root, relative):
    path = root / relative
    for part in (path,) + tuple(path.parents):
        if part == root:
            break
        if part.is_symlink():
            raise HomeRouteError("Symlink is not a valid home route file: " + relative)
    return path


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise HomeRouteError("Duplicate route configuration key: " + key)
        result[key] = value
    return result


class _HomeDocument(HTMLParser):
    def __init__(self, source):
        super().__init__(convert_charrefs=True)
        self.source = source
        self.line_offsets = [0]
        self.line_offsets.extend(match.end() for match in re.finditer("\n", source))
        self.heads = []
        self.bases = 0
        self.ids = Counter()
        self.feed(source)
        self.close()

    def handle_starttag(self, tag, attrs):
        if tag == "head":
            line, column = self.getpos()
            start = self.line_offsets[line - 1] + column
            self.heads.append((start, start + len(self.get_starttag_text())))
        if tag == "base":
            self.bases += 1
        for key, value in attrs:
            if key == "id" and value:
                self.ids[value] += 1

    handle_startendtag = handle_starttag


def _parse_home(source):
    document = _HomeDocument(source)
    if len(document.heads) != 1:
        raise HomeRouteError("index.html must contain exactly one <head> for home route generation")
    if document.bases:
        raise HomeRouteError("index.html already contains <base>; home aliases require a single generated base")
    if HTML_MARKER in source:
        raise HomeRouteError("index.html is a generated alias; restore the original homepage source")
    return document


def load_home_routes(root):
    """Read and validate slug -> existing homepage target ID; absent config is {}."""
    root = Path(root).resolve()
    config = _local_path(root, CONFIG_PATH)
    if not config.exists():
        return {}
    try:
        value = json.loads(_read(config), object_pairs_hook=_unique_object)
    except json.JSONDecodeError as error:
        raise HomeRouteError("Invalid {}: {}".format(CONFIG_PATH, error)) from error
    if not isinstance(value, dict) or set(value) != {"homeRoutes"} or not isinstance(value["homeRoutes"], dict):
        raise HomeRouteError(CONFIG_PATH + ' must contain only a "homeRoutes" object')
    routes = value["homeRoutes"]
    document = _parse_home(_read(_local_path(root, "index.html")))
    for slug, target in routes.items():
        if not SLUG.fullmatch(slug) or slug in RESERVED_SLUGS:
            raise HomeRouteError("Unsafe or reserved home route slug: " + repr(slug))
        if not isinstance(target, str) or not TARGET_ID.fullmatch(target):
            raise HomeRouteError("Invalid home route target for " + slug + ": " + repr(target))
        if document.ids[target] != 1:
            raise HomeRouteError("Home route {} requires exactly one #{} target in index.html".format(slug, target))
        route = _local_path(root, slug)
        if route.exists() and not route.is_dir():
            raise HomeRouteError("Home route collides with an existing file: " + slug)
        if (root / (slug + ".html")).exists():
            raise HomeRouteError("Home route collides with an existing HTML page: " + slug + ".html")
    return routes


def render_home_routes_module(routes):
    """Render the shared browser map deterministically, without build dependencies."""
    return MODULE_MARKER + "\nexport default " + json.dumps(routes, ensure_ascii=True, indent=2) + ";\n"


def render_home_alias(source, base="../", marker=HTML_MARKER):
    """Preserve the complete homepage and insert its portable base first in head."""
    document = _parse_home(source)
    start, end = document.heads[0]
    line_start = source.rfind("\n", 0, start) + 1
    indent = re.match(r"[ \t]*", source[line_start:start]).group(0) + "  "
    newline = "\r\n" if "\r\n" in source else "\n"
    insertion = newline + indent + f'<base href="{base}" />' + newline + indent + marker
    return source[:end] + insertion + source[end:]


def _artifacts(root, routes):
    source = _read(_local_path(root, "index.html"))
    alias = render_home_alias(source)
    artifacts = {MODULE_PATH: render_home_routes_module(routes), **{
        slug + "/index.html": alias for slug in routes
    }}
    locale_config = _local_path(root, LOCALE_CONFIG)
    if locale_config.exists():
        metadata = json.loads(_read(locale_config))
        strings = read_strings(_read(_local_path(root, TRANSLATIONS)), "en")
        for filename in ("index.html", "search-by-parameters.html"):
            english = render_english_page(
                _read(_local_path(root, filename)), strings, metadata[filename], routes
            )
            marker = f"<!-- Generated by scripts/generate-home-routes.py; edit {filename} and the locale sources instead. -->"
            artifacts["en/" + filename] = render_home_alias(english, marker=marker)
            if filename == "index.html":
                for slug in routes:
                    artifacts[f"en/{slug}/index.html"] = render_home_alias(english, "../../", marker)
    return artifacts


def validate_home_routes(root):
    """Return validated routes, rejecting missing/stale generated files.

    Projects without config/site-routes.json are intentionally unaffected. This
    function is also the production builder's preflight and never writes files.
    """
    root = Path(root).resolve()
    routes = load_home_routes(root)
    if not (root / CONFIG_PATH).exists():
        return {}
    for relative, expected in _artifacts(root, routes).items():
        path = _local_path(root, relative)
        if not path.is_file():
            raise HomeRouteError("Missing generated home route file: {}. Run {}.".format(relative, GENERATOR))
        if _read(path) != expected:
            raise HomeRouteError("Stale generated home route file: {}. Run {}.".format(relative, GENERATOR))
    return routes


def generate_home_routes(root):
    """Write reviewed aliases/module after preflighting every output; return routes.

    Existing files are replaced only if they carry this generator's marker. No
    other files are removed or overwritten, including files in route folders.
    """
    root = Path(root).resolve()
    routes = load_home_routes(root)
    if not (root / CONFIG_PATH).exists():
        return {}
    artifacts = _artifacts(root, routes)
    for relative in artifacts:
        path = _local_path(root, relative)
        marker = MODULE_MARKER if relative == MODULE_PATH else (
            "<!-- Generated by scripts/generate-home-routes.py;" if relative.startswith("en/") else HTML_MARKER
        )
        if path.exists() and (not path.is_file() or marker not in _read(path)):
            raise HomeRouteError("Refusing to overwrite a file not owned by the home route generator: " + relative)
        if relative != MODULE_PATH and not relative.startswith("en/") and path.parent.exists():
            foreign = [entry for entry in path.parent.iterdir() if entry.name != "index.html"]
            if foreign:
                raise HomeRouteError("Home route collides with an existing directory: " + path.parent.name)
    for relative, content in artifacts.items():
        path = _local_path(root, relative)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
    return routes
