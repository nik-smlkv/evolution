const makeProperty = (propertyType, unit, area, planLevels) => {
  const labels = planLevels.map((level) => floorLabels[level]);
  return {
    id: `${propertyType}:${unit}`,
    propertyType,
    unit,
    apartmentNumber: unit,
    buldingWing: propertyType === "commercial" ? `Lamela ${unit[0]}` : "",
    floor: labels.join(" / "),
    floorLabels: labels,
    planLevels,
    area,
    image: null,
    apartmentImg: null,
    planImg: null,
  };
};

export const tchaikovskyOtherProperties = [
  ...commercialSpecifications.map(([unit, area, levels]) => makeProperty("commercial", unit, area, levels)),
  ...parkingAreas.map((area, index) => {
    const number = index + 1;
    const level = number <= 141 ? "1400" : number <= 288 ? "1300" : number <= 435 ? "1200" : "1100";
    return {
      ...makeProperty("parking", String(number), area, [level]),
      parkingKind: accessibleParking.has(number) ? "accessible" : evParking.has(number) ? "ev" : "standard",
    };
  }),
];
