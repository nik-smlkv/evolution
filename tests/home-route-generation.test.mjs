import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const generator = fileURLToPath(new URL("../scripts/generate-home-routes.py", import.meta.url));
const routes = { "about-project": "about-project", contact: "contact", "request-callback": "form" };

function fixture(t) {
  const base = mkdtempSync(join(tmpdir(), "evolution-home-routes-"));
  const root = join(base, "project");
  t.after(() => rmSync(base, { recursive: true, force: true }));
  const write = (path, value) => {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), value);
  };
  const source = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8">
    <title>Evolution Residence</title>
    <meta name="description" content="A shared homepage">
    <link rel="canonical" href="https://example.test/evolution/">
    <meta property="og:url" content="https://example.test/evolution/">
    <link rel="stylesheet" href="./style/site.css">
    <script type="module" src="./js/main.js"></script>
  </head>
  <body>
    <section id="about-project"></section>
    <section id="form"></section>
    <footer><div id="contact"></div></footer>
  </body>
</html>
`.replaceAll("\n", "\r\n");
  write("index.html", source);
  write("config/site-routes.json", JSON.stringify({ homeRoutes: routes }));
  return { base, root, source, write };
}

function run(root, args = []) {
  return spawnSync("python3", ["-B", generator, "--root", root, ...args], { encoding: "utf8" });
}

test("generated routes preserve homepage content and metadata with a portable base first in head", async (t) => {
  const { root, source } = fixture(t);
  const generated = run(root);
  assert.equal(generated.status, 0, generated.stderr);
  for (const slug of Object.keys(routes)) {
    const alias = readFileSync(join(root, slug, "index.html"), "utf8");
    assert.match(alias, /<head>\r\n    <base href="\.\.\/" \/>\r\n    <!-- Generated by scripts\/generate-home-routes\.py;/);
    assert.equal(alias.replace(/\r\n    <base href="\.\.\/" \/>\r\n    <!-- Generated by scripts\/generate-home-routes\.py; edit index\.html instead\. -->/, ""), source);
    assert.equal((alias.match(/rel="canonical"/g) || []).length, 1);
    const asset = new URL("./style/site.css", new URL("../", "https://example.test/evolution/" + slug + "/"));
    assert.equal(asset.href, "https://example.test/evolution/style/site.css");
  }
  const module = readFileSync(join(root, "js/home-routes.js"), "utf8");
  assert.deepEqual((await import("data:text/javascript," + encodeURIComponent(module))).default, routes);
  assert.equal(run(root, ["--check"]).status, 0);
});

test("check rejects missing aliases and stale homepage copies or browser maps until regenerated", (t) => {
  const { root, source, write } = fixture(t);
  assert.match(run(root, ["--check"]).stderr, /Missing.*js\/home-routes\.js.*generate-home-routes\.py/);
  assert.equal(run(root).status, 0);
  rmSync(join(root, "contact/index.html"));
  assert.match(run(root, ["--check"]).stderr, /Missing.*contact\/index\.html/);
  assert.equal(run(root).status, 0);
  write("index.html", source.replace("A shared homepage", "The updated homepage"));
  assert.match(run(root, ["--check"]).stderr, /Stale.*about-project\/index\.html/);
  assert.equal(run(root).status, 0);
  write("js/home-routes.js", readFileSync(join(root, "js/home-routes.js"), "utf8").replace('"contact": "contact"', '"contact": "form"'));
  assert.match(run(root, ["--check"]).stderr, /Stale.*js\/home-routes\.js/);
  assert.equal(run(root).status, 0);
  assert.equal(run(root, ["--check"]).status, 0);
});

test("configuration rejects traversal, reserved or existing pages and missing or ambiguous targets", (t) => {
  const { root, source, write } = fixture(t);
  for (const slug of ["../outside", "About", "a/b", "assets", "search-by-parameters"]) {
    write("config/site-routes.json", JSON.stringify({ homeRoutes: { [slug]: "about-project" } }));
    assert.match(run(root).stderr, /Unsafe or reserved home route slug/);
  }
  write("config/site-routes.json", '{"homeRoutes":{"contact":"contact","contact":"form"}}');
  assert.match(run(root).stderr, /Duplicate route configuration key/);
  write("config/site-routes.json", JSON.stringify({ homeRoutes: { missing: "unknown" } }));
  assert.match(run(root).stderr, /requires exactly one #unknown/);
  write("config/site-routes.json", JSON.stringify({ homeRoutes: routes }));
  write("index.html", source.replace('</body>', '<div id="contact"></div></body>'));
  assert.match(run(root).stderr, /requires exactly one #contact/);
  write("index.html", source);
  write("contact.html", "Existing page");
  assert.match(run(root).stderr, /collides with an existing HTML page/);
  assert.equal(existsSync(join(root, "js/home-routes.js")), false);
});

test("generation preflights all outputs and preserves existing foreign pages", (t) => {
  const { root, write } = fixture(t);
  write("contact/index.html", "A separately maintained contact page");
  const result = run(root);
  assert.equal(result.status, 1);
  assert.match(result.stderr, /Refusing to overwrite.*contact\/index\.html/);
  assert.equal(readFileSync(join(root, "contact/index.html"), "utf8"), "A separately maintained contact page");
  assert.equal(existsSync(join(root, "js/home-routes.js")), false);
  assert.equal(existsSync(join(root, "about-project")), false);
});

test("symlink route folders are rejected and projects without route config are unchanged", (t) => {
  const { base, root } = fixture(t);
  const outside = join(base, "outside");
  mkdirSync(outside);
  symlinkSync(outside, join(root, "contact"), "dir");
  assert.match(run(root).stderr, /Symlink is not a valid home route file: contact/);
  assert.equal(existsSync(join(outside, "index.html")), false);
  rmSync(join(root, "config/site-routes.json"));
  rmSync(join(root, "index.html"));
  const checked = run(root, ["--check"]);
  assert.equal(checked.status, 0, checked.stderr);
  assert.equal(existsSync(join(root, "js/home-routes.js")), false);
});
